"""Tests for CVModelAdapter, model loader, tensor ingestion, and coordinate transformation."""

import uuid
import numpy as np
import pytest
from app.core.config import settings
from app.models.cv_model_adapter import CVModelAdapter
from app.models.model_loader import ModelLoader
from app.pipelines.inspection_pipeline import InspectionPipeline


def test_model_loader_metadata_and_device():
    """Verifies that model loader initializes metadata, class list, and target device."""
    model, metadata = ModelLoader.load_model(
        weights_path=None,
        model_name="firesphere-inspection-cv",
        model_version="0.3.0-phase3",
    )

    assert metadata.modelName == "firesphere-inspection-cv"
    assert metadata.modelVersion == "0.3.0-phase3"
    assert metadata.device in ["cuda", "cpu"]
    assert metadata.weightsLoaded is False
    assert metadata.trainingStatus == "NOT_YET_TRAINED"
    assert len(metadata.classes) > 0
    assert "FIRE_EXTINGUISHER_MISSING" in metadata.classes
    # All classes must be honestly reported as unsupported until a trained dataset is supplied
    assert len(metadata.unsupportedClasses) == len(metadata.classes)


def test_prepare_input_tensor_shape_and_transposition():
    """Verifies that (H, W, C) float32 arrays are transposed to (1, C, H, W) batch tensors."""
    # Create sample (640, 640, 3) image
    sample_hwc = np.full((640, 640, 3), 0.5, dtype=np.float32)
    batch_tensor = CVModelAdapter.prepare_input_tensor(sample_hwc)

    assert batch_tensor.shape == (1, 3, 640, 640)
    assert batch_tensor.dtype == np.float32


def test_invalid_input_tensor_raises_error():
    """Verifies that invalid tensor inputs (wrong dimensions or None) raise ValueError."""
    with pytest.raises(ValueError):
        CVModelAdapter.prepare_input_tensor(None)  # type: ignore

    with pytest.raises(ValueError):
        # 2D array instead of 3D
        CVModelAdapter.prepare_input_tensor(np.zeros((640, 640), dtype=np.float32))


def test_baseline_model_produces_no_fake_detections():
    """Verifies that when testMode is False and no weights exist, no detections are fabricated."""
    adapter = CVModelAdapter()
    sample_img = np.full((640, 640, 3), 0.5, dtype=np.float32)

    detections = adapter.predict(
        evidence_id=str(uuid.uuid4()),
        preprocessed_image=sample_img,
        test_mode=False,
    )

    # Must be empty: never fabricate detections without trained model
    assert len(detections) == 0


def test_test_mode_generates_traceable_detections():
    """Verifies that testMode generates synthetic detections with isTestData=True and valid bounding boxes."""
    adapter = CVModelAdapter()
    sample_img = np.full((640, 640, 3), 0.5, dtype=np.float32)
    test_eid = str(uuid.uuid4())

    detections = adapter.predict(
        evidence_id=test_eid,
        preprocessed_image=sample_img,
        test_mode=True,
    )

    assert len(detections) > 0
    det = detections[0]
    assert det.className == "FIRE_EXTINGUISHER_MISSING"
    assert det.confidence >= 0.50
    assert det.boundingBox is not None
    assert 0.0 <= det.boundingBox["xMin"] <= 1.0


def test_pipeline_transforms_bounding_boxes_to_original_image():
    """Verifies that findings generated by the pipeline contain bounding boxes mapped to the original image."""
    pipeline = InspectionPipeline()
    insp_id = uuid.uuid4()
    eid = uuid.uuid4()

    run = pipeline.execute(
        inspection_id=insp_id,
        evidence_ids=[eid],
        test_mode=True,
    )

    assert run.status == "COMPLETED"
    assert len(run.findings) > 0
    finding = run.findings[0]

    # Verify bounding box exists and is normalized in [0, 1]
    assert finding.boundingBox is not None
    assert 0.0 <= finding.boundingBox.xMin <= 1.0
    assert 0.0 <= finding.boundingBox.yMin <= 1.0
    assert 0.0 <= finding.boundingBox.xMax <= 1.0
    assert 0.0 <= finding.boundingBox.yMax <= 1.0
    assert finding.evidenceId == eid
    assert finding.isTestData is True
    assert finding.model == settings.model_name
    assert finding.modelVersion == settings.model_version
