"""Pydantic schemas and contracts for asynchronous AI jobs."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field, field_validator


class JobStatus(str, Enum):
    """Lifecycle states for asynchronous AI inspection jobs."""

    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    RETRYING = "RETRYING"
    CANCELLED = "CANCELLED"


class AIJobCreateRequest(BaseModel):
    """Request payload for dispatching an asynchronous AI inspection job."""

    inspectionId: uuid.UUID = Field(description="UUID reference to the parent inspection docket")
    evidenceIds: List[uuid.UUID] = Field(min_length=1, description="List of evidence image UUIDs to evaluate")
    operation: str = Field(
        default="INSPECTION_ANALYSIS_AND_REPORT",
        description="Target AI operation: INSPECTION_ANALYSIS, INSPECTION_REPORT_DRAFT, or INSPECTION_ANALYSIS_AND_REPORT",
    )
    occupancyContext: str = Field(
        default="UNKNOWN",
        description="Premises occupancy classification (e.g. COMMERCIAL, INDUSTRIAL, RESIDENTIAL)",
    )
    historicalContext: str = Field(
        default="UNAVAILABLE",
        description="Prior inspection compliance record if known",
    )
    testMode: bool = Field(
        default=False,
        description="Whether to run in isolated synthetic test mode with test fixture findings",
    )
    idempotencyKey: Optional[str] = Field(
        default=None,
        description="Client-supplied idempotency key preventing duplicate job creation",
    )
    tenantId: str = Field(
        default="default",
        description="Multi-tenant identifier for enterprise SaaS isolation",
    )
    officerRemarks: Optional[str] = Field(
        default=None,
        description="Optional pre-existing remarks authored by human Fire Safety Officer",
    )
    checklistData: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional checklist observations from municipal inspection schedule",
    )


class AIJobResponse(BaseModel):
    """Structured response containing AI job identity, status, and execution metadata."""

    jobId: uuid.UUID = Field(description="Unique identifier for the AI job")
    inspectionId: uuid.UUID = Field(description="UUID reference to the parent inspection docket")
    tenantId: str = Field(default="default", description="Multi-tenant identifier")
    status: JobStatus = Field(description="Current processing lifecycle status")
    operation: str = Field(description="Target AI processing operation")
    attempt: int = Field(default=1, description="Current execution attempt number")
    maxAttempts: int = Field(default=3, description="Maximum bounded retry attempts")
    idempotencyKey: Optional[str] = Field(default=None, description="Idempotency key associated with job")
    analysisRunId: Optional[uuid.UUID] = Field(
        default=None,
        description="Distinct AI Run ID generated by Phase 1-4 pipeline execution",
    )
    reportId: Optional[uuid.UUID] = Field(
        default=None,
        description="Distinct Report ID generated by Phase 5 report drafting layer",
    )
    errorCode: Optional[str] = Field(default=None, description="Standardized error code if job failed")
    errorMessage: Optional[str] = Field(default=None, description="Sanitized, non-leaking error description")
    modelName: str = Field(description="Name of the computer vision model")
    modelVersion: str = Field(description="Version of the computer vision model")
    serviceVersion: str = Field(description="Version of the AI service")
    correlationId: Optional[str] = Field(default=None, description="End-to-end request correlation identifier")
    createdAt: datetime = Field(description="UTC timestamp of job submission")
    startedAt: Optional[datetime] = Field(default=None, description="UTC timestamp when processing began")
    completedAt: Optional[datetime] = Field(default=None, description="UTC timestamp when processing completed")

    @field_validator("status", mode="before")
    @classmethod
    def validate_job_status_boundary(cls, value: Any) -> Any:
        """Enforces that AI jobs never represent statutory approval or rejection decisions."""
        if isinstance(value, str):
            normalized = value.strip().upper()
            if normalized in ("AI_APPROVED", "AI_REJECTED", "APPROVED", "REJECTED", "AI_NOC_APPROVED", "AI_NOC_REJECTED"):
                raise ValueError(
                    f"Job status '{value}' is strictly forbidden. AI jobs track execution status only and "
                    "cannot autonomously approve or reject Fire NOC compliance."
                )
        return value


class AIJobResultResponse(BaseModel):
    """Complete structured result retrieved upon AI job completion."""

    jobId: uuid.UUID = Field(description="Unique identifier for the AI job")
    inspectionId: uuid.UUID = Field(description="UUID reference to the parent inspection docket")
    tenantId: str = Field(default="default", description="Multi-tenant identifier")
    status: JobStatus = Field(description="Final processing status (COMPLETED or FAILED)")
    analysisRunId: Optional[uuid.UUID] = Field(default=None, description="Associated AI analysis run ID")
    reportId: Optional[uuid.UUID] = Field(default=None, description="Associated report draft ID")
    createdAt: datetime = Field(description="UTC timestamp of job submission")
    completedAt: Optional[datetime] = Field(default=None, description="UTC timestamp of job completion")
    analysis: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured Phase 4 inspection analysis results (findings, summary)",
    )
    report: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured Phase 5 inspection report draft (summary, traceability, etc.)",
    )
    errorCode: Optional[str] = Field(default=None, description="Error code if job failed")
    errorMessage: Optional[str] = Field(default=None, description="Error message if job failed")


class AIJobRecord(BaseModel):
    """Internal persistent record representing an AI job in storage/queue repositories."""

    jobId: uuid.UUID = Field(default_factory=uuid.uuid4)
    inspectionId: uuid.UUID
    tenantId: str = "default"
    status: JobStatus = JobStatus.QUEUED
    operation: str = "INSPECTION_ANALYSIS_AND_REPORT"
    evidenceIds: List[uuid.UUID]
    occupancyContext: str = "UNKNOWN"
    historicalContext: str = "UNAVAILABLE"
    testMode: bool = False
    officerRemarks: Optional[str] = None
    checklistData: Optional[Dict[str, Any]] = None
    idempotencyKey: Optional[str] = None
    correlationId: Optional[str] = None
    attempt: int = 1
    maxAttempts: int = 3
    createdAt: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    startedAt: Optional[datetime] = None
    completedAt: Optional[datetime] = None
    nextRetryAt: Optional[datetime] = None
    analysisRunId: Optional[uuid.UUID] = None
    reportId: Optional[uuid.UUID] = None
    errorCode: Optional[str] = None
    errorMessage: Optional[str] = None
    modelName: str = "firesphere-inspection-cv"
    modelVersion: str = "0.3.0-phase3"
    serviceVersion: str = "0.6.0-phase6"
    resultData: Optional[Dict[str, Any]] = None

    def to_response(self) -> AIJobResponse:
        """Converts internal record to public AIJobResponse schema."""
        return AIJobResponse(
            jobId=self.jobId,
            inspectionId=self.inspectionId,
            tenantId=self.tenantId,
            status=self.status,
            operation=self.operation,
            attempt=self.attempt,
            maxAttempts=self.maxAttempts,
            idempotencyKey=self.idempotencyKey,
            analysisRunId=self.analysisRunId,
            reportId=self.reportId,
            errorCode=self.errorCode,
            errorMessage=self.errorMessage,
            modelName=self.modelName,
            modelVersion=self.modelVersion,
            serviceVersion=self.serviceVersion,
            correlationId=self.correlationId,
            createdAt=self.createdAt,
            startedAt=self.startedAt,
            completedAt=self.completedAt,
        )
