"""Standardized error codes for FireSphere AI Service."""

from enum import Enum


class AIErrorCode(str, Enum):
    """Catalog of structured, audit-traceable error codes for AI service failures."""

    # Request & Validation Errors
    INVALID_REQUEST = "INVALID_REQUEST"
    UNAUTHORIZED_SERVICE = "UNAUTHORIZED_SERVICE"
    VALIDATION_ERROR = "VALIDATION_ERROR"
    JOB_NOT_FOUND = "JOB_NOT_FOUND"

    # Evidence & Storage Errors
    EVIDENCE_NOT_FOUND = "EVIDENCE_NOT_FOUND"
    EVIDENCE_INVALID = "EVIDENCE_INVALID"
    EVIDENCE_CORRUPTED = "EVIDENCE_CORRUPTED"
    EVIDENCE_OVERSIZED = "EVIDENCE_OVERSIZED"
    STORAGE_UNAVAILABLE = "STORAGE_UNAVAILABLE"
    STORAGE_TIMEOUT = "STORAGE_TIMEOUT"
    INTEGRITY_CHECK_FAILED = "INTEGRITY_CHECK_FAILED"

    # Model & Inference Errors
    MODEL_NOT_AVAILABLE = "MODEL_NOT_AVAILABLE"
    MODEL_LOAD_FAILED = "MODEL_LOAD_FAILED"
    INFERENCE_FAILED = "INFERENCE_FAILED"
    IMAGE_DECODE_FAILED = "IMAGE_DECODE_FAILED"
    IMAGE_QUALITY_ERROR = "IMAGE_QUALITY_ERROR"

    # Operational & Execution Errors
    TIMEOUT = "TIMEOUT"
    JOB_TIMEOUT = "JOB_TIMEOUT"
    INFERENCE_TIMEOUT = "INFERENCE_TIMEOUT"
    QUEUE_ERROR = "QUEUE_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    AI_PROCESSING_FAILURE = "AI_PROCESSING_FAILURE"
