def test_m2_m4_request_validation_rejections(client: TestClient):
    """Verify M4 returns structured HTTP 422 for malformed M2 request bodies."""
    # 1. Missing evidenceIds
    resp1 = client.post("/internal/ai/inspection-analysis", json={"inspectionId": str(uuid.uuid4())})
    assert resp1.status_code == 422
    data1 = resp1.json()
    assert data1["status"] == "FAILED"
    assert data1["errorCode"] == "VALIDATION_ERROR"

    # 2. Empty evidenceIds list
    resp2 = client.post(
        "/internal/ai/inspection-analysis",
        json={"inspectionId": str(uuid.uuid4()), "evidenceIds": []},
    )
    assert resp2.status_code == 422
    assert resp2.json()["errorCode"] == "VALIDATION_ERROR"

    # 3. Invalid UUID string
    resp3 = client.post(
        "/internal/ai/inspection-analysis",
        json={"inspectionId": "invalid-uuid-string", "evidenceIds": [str(uuid.uuid4())]},
    )
    assert resp3.status_code == 422
    assert resp3.json()["errorCode"] == "VALIDATION_ERROR"


def test_m2_m4_service_token_authentication(client: TestClient, monkeypatch):
    """Verify service-to-service authentication using X-AI-Service-Token."""
    test_token = "m2-m4-test-auth-token-xyz"
    monkeypatch.setattr(settings, "service_auth_token", test_token)
    monkeypatch.setattr(settings, "auth_enabled", True)

    payload = {
        "inspectionId": str(uuid.uuid4()),
        "evidenceIds": [str(uuid.uuid4())],
        "testMode": True,
    }

    # 1. Missing token header -> 401
    resp_missing = client.post("/internal/ai/inspection-analysis", json=payload)
    assert resp_missing.status_code == 401
    assert resp_missing.json()["errorCode"] == "UNAUTHORIZED_SERVICE"

    # 2. Invalid token header -> 401
    resp_invalid = client.post(
        "/internal/ai/inspection-analysis",
        json=payload,
        headers={"X-AI-Service-Token": "wrong-secret-token"},
    )
    assert resp_invalid.status_code == 401
    assert resp_invalid.json()["errorCode"] == "UNAUTHORIZED_SERVICE"

    # 3. Valid token header -> 200
    resp_valid = client.post(
        "/internal/ai/inspection-analysis",
        json=payload,
        headers={"X-AI-Service-Token": test_token},
    )
    assert resp_valid.status_code == 200
    assert resp_valid.json()["status"] == "COMPLETED"


