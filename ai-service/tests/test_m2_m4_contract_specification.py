def test_m4_authoritative_request_schema():
    """Verify M4 InspectionAnalysisRequest enforces inspectionId, non-empty evidenceIds, and testMode."""
    insp_id = uuid.uuid4()
    ev_ids = [uuid.uuid4(), uuid.uuid4()]

    # Valid payload
    req = InspectionAnalysisRequest(
        inspectionId=insp_id,
        evidenceIds=ev_ids,
        testMode=True,
        occupancyContext="COMMERCIAL_MERCANTILE",
        tenantId="tenant-corp",
    )
    assert req.inspectionId == insp_id
    assert len(req.evidenceIds) == 2
    assert req.testMode is True

    # Empty evidence list rejected
    with pytest.raises(ValidationError):
        InspectionAnalysisRequest(inspectionId=insp_id, evidenceIds=[])

    # Missing inspectionId rejected
    with pytest.raises(ValidationError):
        InspectionAnalysisRequest(evidenceIds=ev_ids)


