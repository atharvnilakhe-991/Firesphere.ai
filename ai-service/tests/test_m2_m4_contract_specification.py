    assert data["status"] == "QUEUED"
    assert data["inspectionId"] == insp_id

    # 2. Query Status
    status_resp = client.get(f"/internal/ai/jobs/{job_id}")
    assert status_resp.status_code == 200
    assert status_resp.json()["jobId"] == job_id

    # 3. Query Result
    result_resp = client.get(f"/internal/ai/jobs/{job_id}/result")
    assert result_resp.status_code == 200
    assert result_resp.json()["jobId"] == job_id


