def test_m4_async_job_contract_lifecycle(client: TestClient):
    """Verify M4 POST /internal/ai/jobs supports full asynchronous job lifecycle."""
    insp_id = str(uuid.uuid4())
    ev_id = str(uuid.uuid4())
    idemp_key = f"key-spec-{uuid.uuid4()}"

    # 1. Submit Job
    payload = {
        "inspectionId": insp_id,
        "evidenceIds": [ev_id],
        "testMode": True,
        "idempotencyKey": idemp_key,
        "tenantId": "tenant-spec",
    }
    resp = client.post("/internal/ai/jobs", json=payload)
